"""CI only: one test login per built-in role on a throw-away database.
Run with:  python manage.py shell < ../e2e/setup_users.py   (E2E_PASSWORD is generated by the CI job)."""
import os

from django.core.management import call_command

from apps.accounts.models import Role, User
from apps.sites.models import Site

assert os.environ.get("E2E_PASSWORD"), "E2E_PASSWORD missing"
assert "localhost" in os.environ.get("DATABASE_URL", ""), "browser-test users go only into the CI database"
pw = os.environ["E2E_PASSWORD"]
call_command("seed", verbosity=0)
site, _ = Site.objects.get_or_create(code="E2E", defaults={"name": "E2E Test Site"})
for n, key in enumerate(["admin", "management", "pm", "purchase", "accounts", "qs", "safety", "engineer", "supervisor", "store"]):
    mobile = f"95000000{n:02d}"
    if key == "admin":
        u = User.objects.create_superuser(mobile, pw, name="E2E Admin")
    else:
        u = User.objects.create_user(mobile, pw, name=f"E2E {key}", role=Role.objects.get(key=key))
    u.sites.add(site)
print("e2e users ready")
